#!/usr/bin/env python
"""Regenerate benchmark_report.md's comparison table from vllm_bench.csv and
sglang_bench.csv.

    python generate_report.py

Run this after both CSVs have real rows in them (i.e. after running
bench_vllm.py and bench_sglang.py against live servers). Also copy the
resulting table into the top-level README's Results section by hand -- kept
manual on purpose so a stale README table can't silently drift from what's
actually in these CSVs.
"""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load_rows(csv_path: Path):
    if not csv_path.exists():
        return []
    with csv_path.open(newline="") as f:
        return list(csv.DictReader(f))


def render_table(rows):
    if not rows:
        return "_(no data yet -- run the bench scripts first)_"

    header = "| Engine | Batch size | Seq len (in/out) | Throughput (tok/s) | p50 latency | p99 latency |"
    sep = "|---|---|---|---|---|---|"
    lines = [header, sep]
    for r in rows:
        seq = f"{r['input_len']}/{r['output_len']}"
        lines.append(
            f"| {r['engine']} | {r['batch_size']} | {seq} | "
            f"{r['throughput_tok_s']} | {r['p50_latency_ms']}ms | {r['p99_latency_ms']}ms |"
        )
    return "\n".join(lines)


def main():
    vllm_rows = load_rows(HERE / "vllm_bench.csv")
    sglang_rows = load_rows(HERE / "sglang_bench.csv")
    all_rows = vllm_rows + sglang_rows

    table = render_table(all_rows)

    report = f"""# Benchmark report

Regenerated by `generate_report.py` from `vllm_bench.csv` and `sglang_bench.csv`.
See [`../../docs/architecture.md`](../../docs/architecture.md) for the sweep methodology
(same synthetic prompts, same batch sizes and sequence lengths, against both engines).

{table}

## Reading this table

- **Throughput (tok/s)** is completion tokens / wall-clock time for the whole
  concurrent batch -- it should generally rise with batch size until the GPU
  saturates.
- **p50 / p99 latency** are per-request latencies within that same batch --
  the gap between them widens under load if an engine's scheduler causes
  some requests to wait significantly longer than others.
- Compare the two engines at matching (batch_size, input_len, output_len)
  rows, not just their best case each.
"""
    out_path = HERE / "benchmark_report.md"
    out_path.write_text(report)
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
